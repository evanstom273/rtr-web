import { writeFileSync } from 'node:fs';
import { expect, it } from 'vitest';
import * as T from './tuning';

const GROUPS: [string, [keyof typeof T, string][]][] = [
  ['1. Companies and founding', [
    ['COMPANY', 'Companies: tiers from popularity, starting banks, roster sizes, office half-days a week, shows a week'],
    ['FOUND', 'Founding your own: the least you can put in, its starting popularity, initials and name'],
  ]],
  ['2. The card', [
    ['SEGMENT', 'Segments: how they’re scored (0–5) and what they do for fans'],
    ['SHOW_RATE', 'The whole show: weights, flow, payoffs, star power, running to time'],
    ['SELF_BOOK', 'Booking yourself: standing, your opponent, the glory-hog talk'],
  ]],
  ['3. Storylines and titles', [
    ['STORY', 'Storylines: heat, turns, betrayals, the AI’s turns'],
    ['BELTS', 'Titles: how many by tier, the cruiserweight limit, an injured champion'],
  ]],
  ['4. The books', [
    ['BIZ', 'Money: tickets, merch, the draw, venues, production, TV, pay-per-view, sponsors, insurance, the overdraft, loans, salary, budget, tiers'],
  ]],
  ['5. Roster, signing and staff', [
    ['SIGN', 'Signing: what someone’s worth, haggling, buyouts, releases, renewals'],
    ['MORALE', 'How your roster feels about you'],
    ['STAFF', 'Staff: candidates, wages, what the best do'],
  ]],
  ['6. Owners and the war', [
    ['OWNER', 'Owners: patience, goals, meddling, buying, selling, being hired'],
    ['WAR', 'The war: poaching, counter-programming, TV, startups, merges'],
  ]],
];

const fmt = (v: unknown): string => (Array.isArray(v) ? (v.every((x) => Array.isArray(x)) ? v.map((x) => `(${(x as unknown[]).join(', ')})`).join(' ') : `[${v.map((x) => (typeof x === 'object' ? JSON.stringify(x) : x)).join(', ')}]`) : String(v));
function rows(prefix: string, v: unknown, out: [string, string][]): void {
  if (v && typeof v === 'object' && !Array.isArray(v)) { for (const [k, x] of Object.entries(v)) rows(prefix ? `${prefix}.${k}` : k, x, out); return; }
  out.push([prefix || '(value)', fmt(v)]);
}

it.skipIf(!process.env.BOOKERNUMBERS)('writes the booker numbers sheet', () => {
  const lines = ['# Booker mode: the numbers', '', 'Every number booker mode uses, for Lyra to approve or change. All of them are proposals; they live in `src/career/tuning.ts` (generated by `BOOKERNUMBERS=1 npx vitest run src/career/bookernumbers.test.ts`). Money is in pounds; a "date" is one show.', ''];
  for (const [title, items] of GROUPS) {
    lines.push(`## ${title}`, '');
    for (const [name, what] of items) {
      const out: [string, string][] = [];
      rows('', T[name], out);
      lines.push(`### ${what} (\`${String(name)}\`)`, '', '| Number | Value |', '|---|---|', ...out.map(([k, v]) => `| ${k} | ${v.replace(/\|/g, '\\|')} |`), '');
    }
  }
  writeFileSync('docs/booker-numbers.md', lines.join('\n'));
  expect(lines.length).toBeGreaterThan(50);
});
