const fmt = (v: unknown): string => (Array.isArray(v) ? (v.every((x) => Array.isArray(x)) ? v.map((x) => `(${(x as unknown[]).join(', ')})`).join(' ') : `[${v.join(', ')}]`) : String(v));
function rows(prefix: string, v: unknown, out: [string, string][]): void {
  if (v && typeof v === 'object' && !Array.isArray(v)) { for (const [k, x] of Object.entries(v)) rows(prefix ? `${prefix}.${k}` : k, x, out); return; }
  out.push([prefix || '(value)', fmt(v)]);
}

it.skipIf(!process.env.NUMBERS)('writes the relationships numbers sheet', () => {
  const lines = ['# Relationships: the numbers', '', 'Every number the relationships redesign uses, for Lyra to approve or change. All of them are proposals; they live in `src/career/tuning.ts` (generated by `NUMBERS=1 npx vitest run src/career/numbers.test.ts`).', ''];
  for (const [title, items] of GROUPS) {
    lines.push(`## ${title}`, '');
    for (const [name, what] of items) {
      const out: [string, string][] = [];
      rows('', T[name], out);
      lines.push(`### ${what} (\`${String(name)}\`)`, '', '| Number | Value |', '|---|---|', ...out.map(([k, v]) => `| ${k} | ${v.replace(/\|/g, '\\|')} |`), '');
    }
  }
  writeFileSync('docs/relationships-numbers.md', lines.join('\n'));
  expect(lines.length).toBeGreaterThan(50);
});
